#!/usr/bin/env node
/**
 * Bake the Plate Designer into a module the admin route can serve.
 *
 * The tool is ONE self-contained HTML file (src/product-dev/plate-designer,
 * with its handoff DEPLOYMENT.md). It is served only to signed-in admins, so it
 * cannot live in public/. Reading it from disk at request time would need the
 * file traced into the Vercel function by hand; a string module ships with the
 * route itself instead.
 *
 * To update the tool: replace np7-plate-designer.html, run this script, commit
 * both. A test fails if the two drift apart.
 *
 * Run: node scripts/plate-designer-embed.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const SRC = "src/product-dev/plate-designer/np7-plate-designer.html";
const OUT = "src/lib/plate-designer-html.generated.ts";

const html = readFileSync(SRC, "utf8");
const sha = createHash("sha256").update(html, "utf8").digest("hex");
writeFileSync(OUT, [
  "/* eslint-disable */",
  "// GENERATED by scripts/plate-designer-embed.mjs from " + SRC + ". Do not edit by hand.",
  `export const PLATE_DESIGNER_SHA256 = ${JSON.stringify(sha)};`,
  `export const PLATE_DESIGNER_HTML: string = ${JSON.stringify(html)};`,
  "",
].join("\n"));
console.log(`wrote ${OUT} (${html.length} chars, sha256 ${sha})`);
